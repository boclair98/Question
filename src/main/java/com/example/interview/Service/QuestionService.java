    /**
     * @param job   직무 (예: "developer")
     * @param type  면접 유형 (예: "personality", "technical")
     * @param count 몇 개의 질문을 랜덤으로 가져올지
     * @return 랜덤으로 섞인 질문 리스트 반환
     */
    public List<String> makeQuestion(String job, String type, int count) {
        List<String> pool;

        if ("personality".equals(type)) {
            pool = personalityQuestions.getOrDefault(job, List.of());
        } else if ("technical".equals(type)) {
            pool = technicalQuestions.getOrDefault(job, List.of());
        } else {
            pool = List.of();
        }

        List<String> mutablePool = new ArrayList<>(pool);
        Collections.shuffle(mutablePool);

        return mutablePool.subList(0, Math.min(count, mutablePool.size()));
    }
